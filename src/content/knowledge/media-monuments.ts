import { L } from "@/content/copy";
import type { MediaAsset } from "@/content/knowledge/schema";

type Shot = {
  id: string;
  file: string;
  credit: string;
  license: string;
  licenseUrl: string;
  attributionRequired: boolean;
  captured?: string;
  caption: [string, string, string, string, string, string];
};

function shot(item: Shot): MediaAsset {
  const file = encodeURIComponent(item.file.replace(/ /g, "_"));
  return {
    id: item.id,
    fileTitle: item.file,
    url: `https://commons.wikimedia.org/wiki/Special:FilePath/${file}?width=1600`,
    pageUrl: `https://commons.wikimedia.org/wiki/File:${file}`,
    credit: item.credit,
    license: item.license,
    licenseUrl: item.licenseUrl,
    attributionRequired: item.attributionRequired,
    caption: L(...item.caption),
    authenticPhotograph: true,
    verified: true,
    captured: item.captured,
  };
}

