function merge(a, b) {
  if (Array.isArray(b) || typeof b !== "object" || b === null) return b;
  const out = { ...a };
  for (const [key, value] of Object.entries(b)) {
    out[key] = merge(a?.[key], value);
  }
  return out;
}

