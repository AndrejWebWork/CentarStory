"""Rebuild reference embeddings with the same grid and dHash the browser uses."""

from __future__ import annotations

import json
import re
import urllib.request
from io import BytesIO
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
MEDIA = ROOT / "src" / "content" / "knowledge" / "media.ts"
SITES = ROOT / "src" / "content" / "knowledge"
OUT = ROOT / "src" / "lib" / "recognition" / "embeddings.ts"


def media_urls() -> dict[str, str]:
    text = MEDIA.read_text(encoding="utf-8")
    urls: dict[str, str] = {}
    for block in re.split(r"\{\s*id:", text)[1:]:
        image_id = re.search(r'"([^"]+)"', block)
        url = re.search(r'url:\s*"([^"]+)"', block)
        if image_id and url:
            urls[image_id.group(1)] = url.group(1)
    return urls


def site_photos() -> list[tuple[str, str]]:
    pairs: list[tuple[str, str]] = []
    for path in sorted(SITES.glob("sites*.ts")):
        text = path.read_text(encoding="utf-8")
        for match in re.finditer(r'images:\s*\[([^\]]*)\]', text):
            images = re.findall(r'"([^"]+)"', match.group(1))
            if not images:
                continue
            before = text[: match.start()]
            slugs = re.findall(r'slug:\s*"([^"]+)"', before)
            if not slugs:
                continue
            for image_id in images:
                pairs.append((slugs[-1], image_id))
    return pairs


def descriptor(image: Image.Image) -> tuple[list[float], str]:
    rgb = image.convert("RGB")
    small = rgb.resize((16, 12), Image.Resampling.BILINEAR)
    pixels = list(small.get_flattened_data())
    vector: list[float] = []
    for cy in range(6):
        for cx in range(8):
            red = green = blue = 0
            for dy in range(2):
                for dx in range(2):
                    r, g, b = pixels[(cy * 2 + dy) * 16 + (cx * 2 + dx)]
                    red += r
                    green += g
                    blue += b
            vector.extend((red / 1020, green / 1020, blue / 1020))
    norm = sum(value * value for value in vector) ** 0.5 or 1
    embedding = [round(value / norm, 5) for value in vector]

    hashed = rgb.resize((9, 8), Image.Resampling.BILINEAR)
    samples = list(hashed.get_flattened_data())
    bits = []
    for y in range(8):
        for x in range(8):
            r1, g1, b1 = samples[y * 9 + x]
            r2, g2, b2 = samples[y * 9 + x + 1]
            left = r1 * 0.299 + g1 * 0.587 + b1 * 0.114
            right = r2 * 0.299 + g2 * 0.587 + b2 * 0.114
            bits.append("1" if left < right else "0")
    return embedding, "".join(bits)


def fetch(url: str) -> Image.Image:
    if url.startswith("/"):
        path = ROOT / "public" / url.lstrip("/")
        return Image.open(path)
    base = url.split("?")[0]
    request = urllib.request.Request(
        f"{base}?width=640",
        headers={"User-Agent": "CentarStory/embeddings"},
    )
    with urllib.request.urlopen(request, timeout=40) as response:
        return Image.open(BytesIO(response.read()))


def main() -> None:
    urls = media_urls()
    records = []
    for slug, image_id in site_photos():
        url = urls.get(image_id)
        if not url:
            raise SystemExit(f"missing media url for {image_id}")
        image = fetch(url)
        embedding, dhash = descriptor(image)
        records.append(
            {
                "dhash": dhash,
                "embedding": embedding,
                "imageId": image_id,
                "slug": slug,
            }
        )
        print(f"{slug} {image_id}")

    body = json.dumps(records, indent=2)
    OUT.write_text(
        """/**
 * Precomputed L2-normalized 144-dimensional spatial RGB embeddings (8x6 grid)
 * and 64-bit perceptual difference hashes (dHash) for verified reference photographs
 * in the CentarStory municipal monument catalogue.
 *
 * Precomputing these descriptors avoids downloading and decoding every catalogue
 * photograph on the visitor device whenever a scan is performed.
 * Regenerated by scripts/build-embeddings.py with the same grid the browser uses.
 */
export type PrecomputedReferenceEmbedding = {
  slug: string;
  imageId: string;
  dhash: string;
  embedding: number[];
};

export const PRECOMPUTED_REFERENCE_EMBEDDINGS: PrecomputedReferenceEmbedding[] = """
        + body
        + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {len(records)} embeddings")


if __name__ == "__main__":
    main()
